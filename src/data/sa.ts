export function categoryById(id: string) {
  return CATEGORIES.find((c) => c.id === id);
}

export function businessBySlug(slug: string) {
  return BUSINESSES.find((b2) => b2.slug === slug);
}

export function businessCountByProvince(provinceName: string) {
  return BUSINESSES.filter((b2) => b2.province === provinceName).length;
}
